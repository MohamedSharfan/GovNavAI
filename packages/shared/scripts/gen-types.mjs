// Generate TypeScript types from the JSON Schemas exported by the agent service.
// Run via `pnpm schemas` from the repo root (exports, then generates).
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const schemaDir = join(root, "schemas");
const files = (await readdir(schemaDir)).filter((f) => f.endsWith(".schema.json")).sort();

const seen = new Set();
const chunks = [
  "/* eslint-disable */\n// AUTO-GENERATED by scripts/gen-types.mjs from packages/shared/schemas. Do not edit.\n",
];
// Pydantic gives every property a `title`, which json-schema-to-typescript turns into
// a named alias (e.g. `type Office = string`) that collides with real interfaces.
// Keep titles only on object definitions.
function stripPropertyTitles(node, isDefinition = false) {
  if (Array.isArray(node)) return node.forEach((n) => stripPropertyTitles(n));
  if (!node || typeof node !== "object") return;
  if (!isDefinition && node.type !== "object") delete node.title;
  for (const [key, value] of Object.entries(node)) {
    if (key === "$defs") Object.values(value).forEach((d) => stripPropertyTitles(d, true));
    // `properties` is a name → schema map: a property may itself be called "title".
    else if (key === "properties") Object.values(value).forEach((d) => stripPropertyTitles(d));
    else stripPropertyTitles(value);
  }
}

for (const file of files) {
  const schema = JSON.parse(await readFile(join(schemaDir, file), "utf8"));
  stripPropertyTitles(schema, true);
  let ts = await compile(schema, schema.title, {
    bannerComment: "",
    additionalProperties: false,
    declareExternallyReferenced: true,
    unreachableDefinitions: false,
    strictIndexSignatures: true,
  });
  // De-duplicate shared $defs (LocalizedText, SourceRef …) emitted by several schemas.
  ts = ts
    .split(/\n(?=export )/)
    .filter((block) => {
      const m = block.match(/^export (?:interface|type) (\w+)/);
      if (!m) return true;
      if (seen.has(m[1])) return false;
      seen.add(m[1]);
      return true;
    })
    .join("\n");
  chunks.push(`// ---- ${file} ----\n${ts.trim()}\n`);
}
await writeFile(join(root, "src", "generated.ts"), chunks.join("\n"));
console.log(`generated src/generated.ts from ${files.length} schemas (${seen.size} types)`);
